"""A welcome message inside a recording: the ``sv.welcomeMessage`` lines of the server settings block.

The ServerInfo ``DataBlock`` (kind 0, see :mod:`bf2demo.serverinfo`) starts with the game name and the welcome message lines, all byte
aligned (``u16`` length + bytes), and the rest of the block follows from the next byte. Replacing the lines therefore only changes the
block's length: the block travels as a ``DataBlock`` header event (kind, length) plus chunk events of at most 63 bytes, so the events of the
block are rebuilt, the event count of the packet is corrected, and every other bit of the packet is copied unchanged. The block is sent at
the join and again at every round start, each copy is rewritten.

The game shows these lines to a connecting client; whether it also shows them when it replays a recording is NOT verified (no test in the game
yet), so clips keep working either way and the viewer offers the signature as an option.
"""

from __future__ import annotations

import struct
from typing import List, Optional, Sequence, Tuple

from .events import EID_BITS, EVENT_NAMES
from .packet import PacketError, parse_packet

CHUNK = 63            # the recorded server never sends more than 63 bytes in one data chunk event
MAX_BLOCK = 8192

#: the message of the exported clips (the user's text, corrected, in a short framed layout; the game's text is Latin-1)
SIGNATURE_LINES: Tuple[str, ...] = (
    "::: BF2Demo Analyzer :::",
    "Welcome, BF2Demo Player!",
    "This file was generated by BF2Demo Analyzer.",
    "By Kakarotto  -  enjoy the replay!",
)

_DATA_BLOCK = next(eid for eid, name in EVENT_NAMES.items() if name == "DataBlock")


def rewrite_server_info(block: bytes, lines: Sequence[str]) -> bytes:
    """``block`` (a kind 0 DataBlock body) with its welcome message lines replaced."""
    name_len = struct.unpack_from("<H", block, 0)[0]
    pos = 2 + name_len
    count = struct.unpack_from("<H", block, pos)[0]
    end = pos + 2
    for _ in range(count):
        end += 2 + struct.unpack_from("<H", block, end)[0]
    body = b"".join(struct.pack("<H", len(raw)) + raw for raw in (line.encode("latin1", "replace") for line in lines))
    return block[:pos] + struct.pack("<H", len(lines)) + body + block[end:]


def _event_bits(is_header: bool, payload: Tuple[int, ...] | bytes) -> Tuple[int, int]:
    """``(value, bit count)`` of a DataBlock event: eid, header flag, then (kind, length) or (length byte, data)."""
    value, pos = _DATA_BLOCK, EID_BITS
    value |= int(is_header) << pos
    pos += 1
    if is_header:
        kind, length = payload                                        # type: ignore[misc]
        value |= kind << pos
        value |= length << (pos + 32)
        return value, pos + 64
    value |= len(payload) << pos                                      # type: ignore[arg-type]
    value |= int.from_bytes(payload, "little") << (pos + 8)           # type: ignore[arg-type]
    return value, pos + 8 + 8 * len(payload)                          # type: ignore[arg-type]


def sign_packet(data: bytes, lines: Sequence[str] = SIGNATURE_LINES) -> Optional[bytes]:
    """The packet with every kind 0 data block rewritten, or ``None`` when it holds no such block."""
    try:
        pkt = parse_packet(data)
    except PacketError:
        return None
    events = pkt.events
    runs: List[Tuple[int, int]] = []                                  # (first event index, last event index) of each kind 0 block
    i = 0
    while i < len(events):
        ev = events[i]
        if ev.name == "DataBlock" and ev["is_header"] and ev["kind"] == 0:
            need, j = ev["length"], i + 1
            while need > 0 and j < len(events) and events[j].name == "DataBlock" and not events[j]["is_header"]:
                need -= len(events[j]["data"])
                j += 1
            if need != 0:
                return None                                           # the block continues in another packet: leave it alone
            runs.append((i, j - 1))
            i = j
        else:
            i += 1
    if not runs:
        return None
    value = int.from_bytes(data, "little")
    out, pos, cursor, count = 0, 0, 0, len(events)
    for first, last in runs:
        start, end = events[first].bit_start, events[last].bit_end
        keep = (value >> cursor) & ((1 << (start - cursor)) - 1)
        out |= keep << pos
        pos += start - cursor
        block = b"".join(events[k]["data"] for k in range(first + 1, last + 1))
        new = rewrite_server_info(block, lines)
        if len(new) > MAX_BLOCK:
            return None
        pieces = [_event_bits(True, (0, len(new)))] + [_event_bits(False, new[o:o + CHUNK]) for o in range(0, len(new), CHUNK)]
        for bits, n in pieces:
            out |= bits << pos
            pos += n
        count += len(pieces) - (last - first + 1)
        cursor = end
    tail = pkt.end_bit - cursor
    out |= ((value >> cursor) & ((1 << tail) - 1)) << pos
    pos += tail
    if count > 255:
        return None
    out = (out & ~(0xFF << 2)) | (count << 2)                         # events count: bits 2..9 (PlayerAction flag, events flag, count)
    return out.to_bytes((pos + 7) // 8, "little")

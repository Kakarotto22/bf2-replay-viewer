"""Render DATA.md: the catalogue of everything a .bf2demo can hold, the event survey of all samples and the open puzzles.

usage: python scripts/build_data_doc.py [samples_dir] > DATA.md      (reads every samples/*.bf2demo, slow: about 3 minutes)
"""
import collections, glob, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from bf2demo.events import EVENT_NAMES                      # noqa: E402
from bf2demo.inventory import CATALOG, NEVER                 # noqa: E402
from bf2demo.reader import load_demo                         # noqa: E402
from bf2demo.replay import build_replay                      # noqa: E402

root = sys.argv[1] if len(sys.argv) > 1 else "samples"
files = sorted(glob.glob(os.path.join(root, "**", "*.bf2demo"), recursive=True))
seen_in = collections.Counter()
total = collections.Counter()
example = {}
for path in files:
    try:
        rep = build_replay(load_demo(path))
    except Exception:                                         # a damaged sample must not stop the survey
        continue
    names = set()
    for _, ev in rep.events:
        names.add(ev.name)
        total[ev.name] += 1
        example.setdefault(ev.name, list(ev.fields))
    seen_in.update(names)
n = len(files)

out = ["# What a `.bf2demo` contains", "",
       "Generated by `scripts/build_data_doc.py` from `bf2demo/inventory.py` and the samples; do not edit by hand.", "",
       "Time: the simulation runs at 30 ticks per second (`bf2demo/timeline.py`). Print what one demo holds with "
       "`python -m bf2demo DEMO --inventory`.", "", "## Data kinds", ""]
for cat in CATALOG:
    out += [f"### {cat.title}", "",
            f"* **Source:** {cat.source}", f"* **Exactness:** {cat.exactness}", f"* **Contains:** {cat.contents}",
            f"* **Read it with:** `{cat.use}`" if cat.use else "", f"* **Note:** {cat.notes}" if cat.notes else "", ""]
out = [l for l in out if l != "" or True]
out += ["## Never in a demo", ""] + [f"* **{what}** - {why}" for what, why in NEVER] + ["", f"## Events ({len(EVENT_NAMES)} kinds, survey of {n} samples)", "",
        "| id | event | samples | total | fields |", "|---|---|---|---|---|"]
for eid, name in sorted(EVENT_NAMES.items()):
    fields = ", ".join(f"`{f}`" for f in example.get(name, [])) or "(never seen: layout from the binary only)"
    out.append(f"| {eid} | {name} | {seen_in.get(name, 0)} | {total.get(name, 0)} | {fields} |")

KNOWN = {"flag_holder", "flag_team", "reserved"}                       # named fields that only look like placeholders
out += ["", "## Events never seen - and where the same information arrives instead", "",
        "* `JoinSquad`, `LeaveSquad`, `Invite`: squad membership is the `squad_id` of the Player ghost, invitations its `squad_invite_mask` (`--report squads`).",
        "* `UAV`, `SupplyDrop`, `DropVehicle`: UAVs arrive as `PostRemote` UAVVehicleCreated/Destroyed and `uav_pred` objects, supply crates as `supply_crate` objects, "
        "vehicle drops as `parachute` objects and AddParachuteToDropVehicle (`--report commander`).",
        "* `Spotted`, `RadioMessage`: spotting and the medic/ammo/repair/revive calls arrive as `PostRemote` HUD events (`--report radio`); the `RadioMessage` event itself is never stored.",
        "* `Rank`: the rank is in the Player ghost. `EndOfRound`: the recorder stops when the round ends, so it is never stored (the report infers the ending).",
        "* `KickBan`, `ChangePlayerName`, `Unlock`, `CommanderCam`, `ToggleFreeCamera`, `VoipPlayerMute`, `VoipSession`, `ContentCheck`, `PythonCommand`, `Request`, "
        "`StringBlock`, `TargetDirection`, `UpdateTrigger`, `PlayerTearGassed`, `SetNightVision`, the grappling hook events and the connection setup events: "
        "not in any sample (layout from the binary only)."]

# open puzzles: every field whose name is still a placeholder
generic = re.compile(r'"((?:unk|flag|value|byte|state|bits|angle|stance|aim|reserved|constant|tail)_?[0-9a-z_]*)"')
out += ["", "## Open puzzles (fields decoded bit-exactly but not named by the binary)", ""]
for path in ("bf2demo/events.py", "bf2demo/objectnet.py", "bf2demo/networkables.py", "bf2demo/serverinfo.py"):
    names = sorted(set(m.group(1) for m in generic.finditer(open(path, encoding="utf-8").read()) if re.search(r"_[0-9a-f]+$|^(unk|flag|reserved|constant)", m.group(1)) and m.group(1) not in KNOWN))
    if names:
        out.append(f"* `{path}`: " + ", ".join(f"`{x}`" for x in names))
print("\n".join(out))
